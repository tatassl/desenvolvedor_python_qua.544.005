# lisat de cidades
cidades = ["Rio de janeiro", "Brasilia", "São Paulo", "Goiânia", "Cuiabá"]  

# ordena a lista
cidades.sort()

# exibe a lista em ordem alfabetica 
for cidade in cidades:
    print(cidade)

# reverte a lista
cidades.sort(reverse=True)

# exibe a lista em ordem reversa
for cidade in cidades:
    print(cidade)